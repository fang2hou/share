/** Takes over the static favicon link; tracks color-scheme changes from here on. */
export function mountFavicon(): void {
  link = document.querySelector('link[rel="icon"]') ?? undefined;
  if (!link) {
    link = document.createElement("link");
    link.rel = "icon";
    document.head.appendChild(link);
  }
  const mq = matchMedia("(prefers-color-scheme: dark)");
  dark = mq.matches;
  mq.addEventListener("change", (e) => {
    dark = e.matches;
    apply();
  });
  apply();
}

